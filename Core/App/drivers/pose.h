#ifndef POSE_H
#define POSE_H

/* ============================================================================
 * 位姿推算（2026-09-26 CARD-005，nav-replay 分支）
 *
 * 航位推算：左右轮位移 + 陀螺航向，中点积分法（照马铃薯 drive_odometry 裁剪）。
 * 坐标系（钉死符号，写错整张图镜像）：
 *   发车点为原点，x 车头方向、y 车身右侧（右系顺时针，与马铃薯一致）。
 *   ψ 顺时针为正（右转增），与 GZ 左正相反。
 *
 * ★只做感知+记录，一行控制代码都没有。
 * ==========================================================================*/

void  pose_reset(void);        /* x=y=ψ=0（上拍里程同步重采） */
void  pose_step(void);         /* 每控制拍(10ms)调一次（与 odom_update 同一处） */
float pose_get_x_mm(void);
float pose_get_y_mm(void);
float pose_get_yaw_deg(void);  /* 顺时针为正(右转增)，与 GZ 左正相反 */

#endif /* POSE_H */
