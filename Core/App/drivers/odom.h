#ifndef ODOM_H
#define ODOM_H

#include <stdint.h>

/* ============================================================================
 * 里程计（2026-09-23 新增）
 *
 * 用途：量"小车跑了多少距离"。目标是用它做出葫芦圈的**强制右转**：
 *       先测出"从起点到葫芦圈出口"的里程，之后到那个里程就强制右转。
 *
 * ★为什么需要单独一层：TIM3/TIM4 配的是 16 位（Period=65535），
 *   `__HAL_TIM_GET_COUNTER` 会在 0..65535 之间回绕 →
 *   直接读两个时间点的差会在回绕时得到巨大错误值。
 *   这里每拍读一次、按【带符号的 16 位差】累加，回绕天然安全。
 *
 * 两个量，别搞混：
 *   · 净位移 distance_mm()      —— **这才是"从起点跑出去多远"**，做强制右转用它
 *   · 累计路程 path_len_mm()    —— 用来判断"跑了多少路"
 *
 * ★★★ 2026-09-23 重要变更：里程改成【取绝对值】累加 ★★★
 *   实车抓到 bug：左右轮正交解码方向相反（A/B 相接反）→
 *   旧的带符号求和 (d_l + d_r)/2 会**互相抵消**，里程读不出来
 *   （现象：单独转两个轮子，OD 几乎不涨；当时读到的 403/400mm 其实是
 *    "车转了多少"的混合量，不是里程）。
 *   修法：(|d_l| + |d_r|) / 2 —— 与接线方向无关，不用标定符号。
 *   ★修好后实测：发车 → 葫芦圈出口 的全程 = **24847mm**。
 *   ⚠️ 代价：**倒退也当正数累加**，所以 distance_mm() 现在恒 >= 0、
 *      只增不减，语义 = "走了多少路"（正是本用途要的量）。
 *      要恢复"带符号净位移"：见 odom.c 里的说明。
 * ==========================================================================*/

void    odom_init(void);          /* 复位里程（上电时调一次） */
void    odom_update(void);        /* 每控制周期(10ms)调一次 */
void    odom_reset(void);         /* 把里程清零，重新开始计（可串口触发） */

int32_t odom_distance_mm(void);   /* ★里程(mm)。取绝对值累加 → 恒 >= 0、只增不减 */
int32_t odom_path_mm(void);       /* 累计路程(mm)，同上（现在两者等价） */
int32_t odom_left_mm(void);       /* 左轮净位移(mm)，单独看两轮是否一致 */
int32_t odom_right_mm(void);      /* 右轮净位移(mm) */

#endif /* ODOM_H */
