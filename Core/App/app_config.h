#define LINE_OS_SAMPLES      8    /* 每拍突发读几次（1~64）。越大越稳, 但一拍内耗时 = N×(间距+0.22µs) */
#define LINE_OS_SPACING_US   1    /* 两次子采样之间的间隔(µs)。0 = 背靠背(最快) */
/* 算例：N=8、间距 1µs → 一拍内 = 8×1.22 ≈ 10µs（占 10ms 的 0.1%，可忽略） */

