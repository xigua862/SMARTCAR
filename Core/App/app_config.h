/* ===========================================================================
 * ★★★ 2026-09-26【转向环"曲率记忆"】—— 第 2 版：增长/衰减不对称 ★★★
 *     第 1 版（UP=DOWN=0.20、加性泄漏 3）实车失败："到相切点疯狂摆头"。
 *     第 2 版把"放手"做得比"抓住"快 4 倍，并按用户要求把前馈占比压小（约 40%）。
 *     仍无效就把 USE_CORR_TRIM 改 0 回到纯 PD —— 一个宏，不用改代码。
 *
 *  ■ 病根（结构性的，不是调参能消掉的）—— 这一节是两次实验最有价值的结论
 *    转向环是【纯 PD】：`corr = KP*e + KD*(e-last_e)`（line_follow.c 里那行）。
 *    而"沿一个半径 R 的圆走"需要一个【恒定的差速】(corr = D_req)。
 *    PD 只在"有误差"时才输出差速 → 为了顶住 D_req，车必须维持一个
 *    【恒定的稳态偏差】：  e_ss = D_req / KP        ← 就是这个量把车"锁"在圆上
 *
 *  ■ 为什么它正好解释了葫芦圈
 *    在相切点上，走线要从圆 1 跨到圆 2、曲率【反号】：
 *    转向必须从 +D_req 翻到 −D_req。而误差得先扫过 ±e_ss 才能把
 *    比例项翻过来 → **e_ss 越大，越翻不过来**。KP 越小 e_ss 越大。
 *      · app_config.h 原作者记录："上一版感觉能过是 KP=3.0 时；
 *        降到 2.5 后转不过相切点了（转向力度不够）"
 *      · 而 KP 现在是 2.0（09-25 为了治"疯狂甩头"从 2.5 降下来的）
 *    ⇒ 本项目的 KP 在 2.0~3.0 之间来回：调大→甩头，调小→过不了相切点。
 *      **这是死循环，因为病根不在 KP，在 e_ss 这个恒定偏差上。**
 *
 *  ■ 做法（第 2 版）：给转向环补一个【带泄漏 + 不对称】的转向微调
 *      err = corr − trim
 *      trim += err > 0 ? err*UP : err*DOWN       // 慢进快出（不对称是关键）
 *      trim −= sign(trim) * LEAK                 // 泄漏：直道上慢慢归 0
 *      corr  = KP*e + KD*de + trim
 *
 *
 *    ★为什么"带泄漏"是关键：纯积分 09-24 试过 → 摆头（积分在直道/出入口
 *      来回绕、且会 windup）。泄漏把它限制成【有限记忆】：
 *        稳态微调 / 稳态 corr = gain / leak = 0.20 / 3 ≈ 0.067
 *        → 圆上恒定差速的约 7% 由微调顶住，93% 仍由 P 项承担。
 *      ⇒ 这一版是【保守起步】：不会让车突然变激进，也不会 windup。
 *
 *  ■ 定量预期（上车判据，不是感觉）
 *      设圆上需要的差速 D_req = 12（26 速度、葫芦圈半径量级）：
 *        纯 PD : e_ss = 12/2.0 = 6.0
 *        加微调: e_ss ≈ 4.1（微调顶住约 40%）→ 换向距离 77mm → 53mm
 *      ⚠️ 第 1 版我写过"微调会在相切点 ~8 拍内自行泄光"——【实测证伪】：
 *         泄漏 3/拍 只抵掉 UP×trim=0.2×trim，净残留 0.8/拍 → 8 拍后仍有 17%。
 *      ⇒ 教训（第 2 版的全部依据）：泄漏式慢积分在"指令突变"处不会自动放手，
 *        必须让【衰减速率 >> 增长速率】—— DOWN > UP 这条不变式就是它。
 *
 *  ■ 直道 / 直角弯 / 十字 不受影响
 *      直道：需要的差速本来就是 0 → trim 泄漏到 0，与原来完全一致。
 *      （仅此处成立；相切点【不】成立，见上面的实测证伪。）
 *
 *  ■ 安全 / 回退
 *      CORR_TRIM_MAX 硬限幅，任何情况下都不会比纯 PD 更激进。
 *      改 USE_CORR_TRIM 0 → 立刻回到"纯 PD"的历史行为（一个宏，不用改代码）。
 * ==========================================================================*/
#define USE_CORR_TRIM        1      /* 1=启用转向环曲率记忆（当前）；0=纯 PD（第1版前的行为）*/
#define CORR_TRIM_MAX        25     /* 微调限幅（PWM 单位）。26 速度下圆上所需差速远小于它 */
#define CORR_TRIM_UP         0.06f  /* ★增长速率/拍（慢进）。0.06 → 时间常数 ≈17 拍 ≈170ms */
#define CORR_TRIM_DOWN       0.25f  /* ★衰减速率/拍（快出）。必须远大于 UP！见下"不变式" */
#define CORR_TRIM_LEAK       0.45f  /* 泄漏/拍。0.45 → 稳态微调 ≈ 需求差速的 40%（见下）*/

