/* ===========================================================================
 * ★★ 红外采样过采样（2026-09-23 加）：提高"实际采样频率"
 *
 *  问题：原来每拍（10ms）只读 1 次红外 = 10ms 一次（100Hz）。
 *        车 1.2m/s 时 10ms 走 12mm，而线才 25mm 宽 —— 拍间位移和线宽同量级，
 *        进/出口那种"一闪而过"的图案很容易整拍漏掉 → 时序判据就不稳。
 *
 *  做法：在每个控制拍内部**连读 N 次**（突发采样），再表决合成一次读数。
 *        单次读 8 路只需 ~16 个 CPU 周期（位带读，1 周期/位），72MHz 下 ≈0.22µs，
 *        所以突发采样本身几乎不花时间。
 *
 *  ⚠️ 诚实说明（别指望它是"真·连续采样"）：
 *     这是**突发采样** —— 只在控制拍开始时采一阵，拍与拍之间仍然不采。
 *     真正连续的高频采样需要定时器中断/ADC+DMA（要动 CubeMX 配置）。
 *     但即使如此，同一拍内的多个子样本也足以把"整拍漏掉的窄图案"救回来。
 *  ⚠️ 上限在**模块本身**：GPIO 能读多快是一回事，
 *     红外模块的接收管 + 比较器 + 板载滤波能不能跟上又是另一回事。
 *     间距调到 0 也可能没有更快 —— 以串口实测为准。
 * ===========================================================================*/
