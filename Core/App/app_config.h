/* 十字判定：多路同时触发 → 强制直行（权重表对称，直接给 e=0）
 * ★2026-09-21 关键修正：真十字是"25mm 宽的横线扫过传感条" → 宽图案只持续几拍；
 *   而**葫芦弯出口/直角入口**是"圆切线 + 垂直线"，宽图案会**持续更久**。
 *   → 用持续时间区分：≤CROSS_MAX_FRAMES 拍 = 十字(直行)；超过 = 按"继续沿上次方向转"处理
 *   （原来没有这个上限，所以葫芦弯最后一个圆的出口被误判成十字 → 直行 → 出不去）*/
#define CROSS_ACTIVE_MIN     5           /* 8 路里同时 >= 5 路触发即认为"宽图案" */
#define CROSS_CONFIRM_CNT    2           /* 连续 N 个控制周期确认，防单帧毛刺 */
#define CROSS_MAX_FRAMES     6           /* 宽图案超过 N 拍 → 不是十字（60ms @10ms 周期）*/

/* ★直线提速（2026-09-22 他提的）：长时间保持直线 → 直接冲到 99
   路数控制：慢起快落（连续 N 拍直线才提速；误差一变大立刻回落） */
#define USE_STRAIGHT_BOOST   1
#define STRAIGHT_BOOST_DELAY 100         /* 连续多少拍"直线"才提速（100 拍 = 1 秒）*/
#define STRAIGHT_BOOST_SPEED 95          /* 提速后的目标速度（留 4 的余量，别贴满 99）*/
#define STRAIGHT_BOOST_RAMP  3           /* 每拍最多涨多少（斜坡，防电流冲击/防抖）*/
#define STRAIGHT_BOOST_ERR_MAX 1         /* |误差| ≤ 此值才算"直线" */

/* ★葫芦弯相切点状态机（2026-09-22 他提的方案）
   原理：4 个外切圆之间有 3 个内部相切点，每过一个转向要翻转；
        接近相切点时，下一个圆的弧先从传感条【边缘】出现，再往中间扩散 → "外→内"波。
   做法：检测"最外路亮(≤2路) → 3 拍内扩散到 ≥3 路" = 相切点；
        记一次；丢线时按【翻转后的方向】修正（而不是沿用上次方向）；
        累计 3 次 = 绕完 4 个圆 → 退出。认不出来就照常循迹（兜底不变）。 */
#define USE_GOURD_SM         1
#define GOURD_EDGE_WINDOW    3           /* 最外路亮之后, 多少拍内扩散算一次波 */
#define GOURD_TOTAL          3           /* 相切点个数（4 个外切圆 → 3 个） */
#define GOURD_FLIP_CYCLES    15          /* 检测到相切点后, "翻转修正"保持的拍数 */
#define GOURD_FLIP_ERR       3           /* 翻转修正用的误差幅度 */
/* ★2026-09-22 按实测数据定：车靠通用 PD 就正确进了下一个圆 → "翻转转向"默认关掉
   （强行翻转会把已经走对的车推歪）。要试就改成 1。*/
#define GOURD_USE_FLIP       0

